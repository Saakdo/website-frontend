// Apply saved language on page load
window.onload = function() {
    const savedLanguage = localStorage.getItem('selectedLanguage') || 'en'; // Default to English if no language is set
    switchLanguage(savedLanguage); // Apply the saved language setting on page load
};

// Shrink Navbar on Scroll
window.addEventListener('scroll', function () {
    // Re-select the header every time a scroll event occurs
    const header = document.querySelector('.header, .header2');
    
    if (header) { // Ensure the header exists before modifying its classes
        if (window.scrollY > 50) { // Adjust the scroll threshold if needed
            header.classList.add('shrink');
            console.log('Shrinking');

            if (header.classList.contains('header2')) {
                header.classList.add('black-bg');
                console.log('Header2 turning black');
            }
        } else {
            header.classList.remove('shrink');

            if (header.classList.contains('header2')) {
                header.classList.remove('black-bg');
                console.log('Header2 removing background');
            }
        }
    } else {
        console.log('Header not found');
    }
});



